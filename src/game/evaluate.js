// 返回以红方为正的分值
export function evaluate(g) {
  let score = 0
  const b = g.board
  for (let sq = 0; sq < 90; sq++) {
    const p = b[sq]
    if (p === 0) continue
    const color = colorOf(p)
    const t = typeOf(p)
    const r = Math.floor(sq / 9), c = sq % 9
    // 红方直接查表; 黑方镜像行
    const pst = PST[t][color === RED ? r : 9 - r][c]
    const v = PIECE_VALUE[t] + pst
    score += color === RED ? v : -v
  }
  return score
}
